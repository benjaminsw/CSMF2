# Durable file primitives
# ---------------------------------------------------------------------------
def fsync_dir(d: Path) -> None:
    fd = os.open(str(d), os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def _hook(hook, stage: str) -> None:
    if hook is not None:
        hook(stage)


def write_durable_new(path: Path, data: bytes, hook=None) -> str:
    """tmp -> fsync -> no-clobber link to final -> unlink tmp -> dir fsync.
    Refuses an existing final path. Returns sha256 of the bytes on disk."""
    require(not path.exists(), "ARTIFACT_EXISTS", str(path))
    tmp = path.with_name(f".tmp.{path.name}.{os.getpid()}")
    with open(tmp, "xb") as fh:
        fh.write(data)
        fh.flush()
        os.fsync(fh.fileno())
    _hook(hook, "durable:tmp_fsynced")
    got = sha256_file(tmp)
    require(got == sha256_bytes(data), "WRITE_READBACK", str(path))
    try:
        os.link(tmp, path)
    except FileExistsError:
        os.unlink(tmp)
        fail("ARTIFACT_EXISTS", str(path))
    os.unlink(tmp)
    fsync_dir(path.parent)
    return got


# ---------------------------------------------------------------------------
# Hash-chained append-only ledger
# ---------------------------------------------------------------------------
LEDGER_SCHEMA = "seqref-v05lt-ledger/1"
GENESIS = "GENESIS"


class Ledger:
    def __init__(self, path: Path):
        self.path = Path(path)

    def _scan(self) -> tuple:
        """-> (records, committed_bytes, torn_tail_bytes)."""
        if not self.path.exists():
            return [], 0, b""
        data = self.path.read_bytes()
        end = data.rfind(b"\n") + 1          # 0 if no complete line
        body, tail = data[:end], data[end:]
        recs, prev = [], GENESIS
        for n, line in enumerate(body.split(b"\n")[:-1]):
            try:
                rec = json.loads(line)
            except ValueError:
                fail("LEDGER_CORRUPT", f"{self.path}: line {n} not JSON")
            if canonical_json(rec) != line:
                fail("LEDGER_CORRUPT", f"{self.path}: line {n} not canonical")
            body = {k: v for k, v in rec.items() if k != "self"}
            if rec.get("self") != sha256_bytes(canonical_json(body)):
                fail("LEDGER_CORRUPT", f"{self.path}: line {n} self-hash "
                     "mismatch (record altered)")
            if rec.get("schema") != LEDGER_SCHEMA or rec.get("seq") != n \
                    or rec.get("prev") != prev:
                fail("LEDGER_CORRUPT", f"{self.path}: line {n} breaks the "
                     f"chain (seq {rec.get('seq')}, prev {rec.get('prev')})")
            recs.append(rec)
            prev = sha256_bytes(line)
        return recs, end, tail

    def records(self) -> list:
        recs, _, tail = self._scan()
        require(not tail, "LEDGER_TORN_TAIL_PENDING",
                f"{self.path}: {len(tail)} uncommitted bytes; run recover()")
        return recs

    def head(self) -> tuple:
        recs = self.records()
        if not recs:
            return -1, GENESIS
        return recs[-1]["seq"], sha256_bytes(canonical_json(recs[-1]))

    def recover(self, quarantine: Path) -> int:
        """Remove an unterminated final line (never a complete one); the
        removed bytes are kept in quarantine. Returns bytes removed."""
        _, end, tail = self._scan()
        if not tail:
            return 0
        quarantine.mkdir(parents=True, exist_ok=True)
        q = quarantine / f"{self.path.name}.torn_tail.{utc_now()}.bin"
        write_durable_new(q, tail)
        with open(self.path, "r+b") as fh:
            fh.truncate(end)
            fh.flush()
            os.fsync(fh.fileno())
        logger.warning("[V05LTC] LEDGER_TORN_TAIL_RECOVERED: %d bytes of an "
                       "uncommitted record moved to %s", len(tail), q)
        return len(tail)

    def append(self, kind: str, body: dict, hook=None) -> str:
        seq, prev = self.head()
        rec = {"schema": LEDGER_SCHEMA, "seq": seq + 1, "prev": prev,
               "time_utc": utc_now(), "kind": kind, "body": body}
        rec["self"] = sha256_bytes(canonical_json(rec))
        line = canonical_json(rec)
        require(b"\n" not in line, "LEDGER_LINE_INVALID", "newline in record")
        new = not self.path.exists()
        _hook(hook, "ledger:before_write")
        fd = os.open(str(self.path), os.O_WRONLY | os.O_APPEND | os.O_CREAT,
                     0o644)
        try:
            payload = line + b"\n"
            done = 0
            while done < len(payload):
                done += os.write(fd, payload[done:])
            os.fsync(fd)
        finally:
            os.close(fd)
        if new:
            fsync_dir(self.path.parent)
        _hook(hook, "ledger:after_fsync")
        return sha256_bytes(line)


# ---------------------------------------------------------------------------
# Crash-safe artefact store (checkpoints and other large artefacts)
# ---------------------------------------------------------------------------
COMMIT_KIND = "commit"


class ArtifactStore:
    """Directory of immutable, uniquely named artefacts whose retained set
    is defined by the last COMMIT record in the ledger."""

    def __init__(self, directory: Path, ledger: Ledger, quarantine: Path):
        self.dir = Path(directory)
        self.ledger = ledger
        self.quarantine = Path(quarantine)
        self.dir.mkdir(parents=True, exist_ok=True)
        self._staged: dict = {}

    @staticmethod
    def sidecar(name: str) -> str:
        return name + ".sha256"

    def last_commit(self):
        recs = [r for r in self.ledger.records() if r["kind"] == COMMIT_KIND]
        return recs[-1] if recs else None

    def committed(self) -> dict:
        last = self.last_commit()
        return dict(last["body"]["retained"]) if last else {}

    def stage(self, name: str, writer: Callable, hook=None) -> str:
        """writer(fileobj) writes the artefact. Returns its sha256."""
        require("/" not in name and not name.startswith(".")
                and not name.endswith(".sha256"), "ARTIFACT_NAME", name)
        final, side = self.dir / name, self.dir / self.sidecar(name)
        require(not final.exists() and not side.exists(), "ARTIFACT_EXISTS",
                str(final))
        tmp = self.dir / f".tmp.{name}.{os.getpid()}"
        with open(tmp, "xb") as fh:
            _hook(hook, "stage:tmp_open")
            writer(fh)
            fh.flush()
            os.fsync(fh.fileno())
        _hook(hook, "stage:tmp_fsynced")
        digest = sha256_file(tmp)            # hash of the bytes on disk
        _hook(hook, "stage:hashed")
        write_durable_new(side, f"{digest}  {name}\n".encode(), hook)
        _hook(hook, "stage:sidecar_written")
        try:
            os.link(tmp, final)
        except FileExistsError:
            fail("ARTIFACT_EXISTS", str(final))
        os.unlink(tmp)
        fsync_dir(self.dir)
        _hook(hook, "stage:linked")
        self._staged[name] = digest
        return digest

    def _listing(self) -> set:
        return {p.name for p in self.dir.iterdir()}

    def commit(self, retained: dict, kind_body: dict, hook=None) -> str:
        """retained: {role: name}. Every name must be newly staged or in
        the previous commit. Previous files not retained are superseded and
        deleted only after the commit record is durable."""
        prev = self.committed()
        prev_names = {v["name"]: v["sha256"] for v in prev.values()}
        expect = (set(prev_names) | set(self._staged))
        expect |= {self.sidecar(n) for n in expect}
        listing = self._listing()
        require(listing == expect, "STORE_DIR_UNEXPECTED",
                f"extra {sorted(listing - expect)[:5]} "
                f"missing {sorted(expect - listing)[:5]}")
        ret = {}
        for role, name in sorted(retained.items()):
            if name in self._staged:
                sha = self._staged[name]
            else:
                require(name in prev_names, "STORE_UNKNOWN_ARTIFACT",
                        f"{role}: {name}")
                sha = prev_names[name]
                side = (self.dir / self.sidecar(name)).read_text().split()[0]
                require(side == sha, "STORE_SIDECAR_MISMATCH", name)
            ret[role] = {"name": name, "sha256": sha}
        kept = {v["name"] for v in ret.values()}
        unused = set(self._staged) - kept
        require(not unused, "STORE_STAGED_UNUSED", str(sorted(unused)[:5]))
        superseded = sorted(set(prev_names) - kept)
        body = dict(kind_body)
        body.update({"retained": ret, "superseded": superseded,
                     "store": str(self.dir)})
        _hook(hook, "commit:before_ledger")
        rec_sha = self.ledger.append(COMMIT_KIND, body, hook)
        _hook(hook, "commit:after_ledger")
        self._staged = {}
        for n in superseded:
            for f in (n, self.sidecar(n)):
                (self.dir / f).unlink()
                _hook(hook, f"commit:deleted:{f}")
        fsync_dir(self.dir)
        return rec_sha

    def recover(self, verify_hashes: bool = True) -> dict:
        """Bring the directory back to the last committed state. Returns
        that commit's body ({} if none). Moves uncommitted artefacts to
        quarantine; completes deletion of superseded ones; any problem
        with a committed artefact -> failed_validity."""
        self.ledger.recover(self.quarantine)
        last = self.last_commit()
        body = last["body"] if last else {}
        keep = {v["name"]: v["sha256"]
                for v in body.get("retained", {}).values()}
        sup = set(body.get("superseded", []))
        for name, sha in sorted(keep.items()):
            f, s = self.dir / name, self.dir / self.sidecar(name)
            require(f.is_file(), "STORE_COMMITTED_MISSING", str(f))
            require(s.is_file() and s.read_text().split()[0] == sha,
                    "STORE_SIDECAR_MISMATCH", name)
            if verify_hashes:
                got = sha256_file(f)
                require(got == sha, "STORE_HASH_MISMATCH",
                        f"{name}: {got} != committed {sha}")
        moved, deleted = [], []
        qdir = self.quarantine / f"store.{utc_now()}"
        for name in sorted(self._listing()):
            base = name[:-len(".sha256")] if name.endswith(".sha256") else name
            if base in keep:
                continue
            if base in sup:
                (self.dir / name).unlink()
                deleted.append(name)
                continue
            qdir.mkdir(parents=True, exist_ok=True)
            shutil.move(str(self.dir / name), str(qdir / name))
            moved.append(name)
        fsync_dir(self.dir)
        if moved:
            logger.warning("[V05LTC] STORE_UNCOMMITTED_QUARANTINED: %s -> %s",
                           moved, qdir)
        if deleted:
            logger.warning("[V05LTC] STORE_SUPERSEDED_DELETION_COMPLETED: %s",
                           deleted)
        self._staged = {}
        return body
