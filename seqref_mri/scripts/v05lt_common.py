def make_dataset(data_root, split: str, mode: str, factory=None):
    """Only split='train' is allowed: the production split='val' IS the
    V02 holdout (195 §2)."""
    if split != "train":
        fail("HOLDOUT_CONTACT", f"split={split!r} requested; the production "
             "'val' split is the V02 holdout, forbidden before 195 §9.3")
    if factory is None:
        from seqref_mri.src.fastmri_data import FastMRISliceDataset
        factory = FastMRISliceDataset
    return factory(str(data_root), split="train", mode=mode)


class SplitView:
    """Ordered selection of production-dataset positions. Items are
    returned unchanged; each item's volume ID is re-checked against the
    allowed set (defence in depth)."""

    def __init__(self, base, positions: list, allowed: frozenset,
                 role: str):
        self.base = base
        self.positions = list(positions)
        self.allowed = allowed
        self.role = role

    def __len__(self) -> int:
        return len(self.positions)

    def entry(self, i: int) -> tuple:
        path, s = self.base.index[self.positions[i]]
        return Path(path).relative_to(self.base.data_root).as_posix(), int(s)

    def __getitem__(self, i: int) -> dict:
        item = self.base[self.positions[i]]
        vid = Path(item["meta"]["file"]).name
        if vid not in self.allowed:
            fail("SPLIT_VIEW_FOREIGN_ITEM", f"{self.role}: {vid}")
        return item

    def set_training_epoch(self, epoch_1based: int) -> None:
        """195 §3: training epoch e uses the production set_epoch(e - 1)."""
        require(self.role == "train", "SET_EPOCH_ROLE",
                f"set_training_epoch on {self.role} view")
        require(isinstance(epoch_1based, int) and epoch_1based >= 1,
                "SET_EPOCH_INVALID", repr(epoch_1based))
        self.base.set_epoch(epoch_1based - 1)

    def order_lines_sha256(self) -> str:
        """AM2-A identity: sha256 of '<relpath>|<slice>\\n' lines in order."""
        h = hashlib.sha256()
        for i in range(len(self)):
            rel, s = self.entry(i)
            h.update(f"{rel}|{s}\n".encode("utf-8"))
        return h.hexdigest()


def build_split_views(data_root, split_doc: dict, holdout: frozenset,
                      expect: SplitExpect = REGISTERED_SPLIT,
                      factory=None) -> tuple:
    """Training view (mode='train', base order L) and validation view
    (mode='eval'), both over split='train', restricted to the manifest."""
    tr_ids = frozenset(r["volume_id"] for r in split_doc["train"])
    va_ids = frozenset(r["volume_id"] for r in split_doc["validation"])
    assert_no_holdout(tr_ids | va_ids, holdout, "split manifest")
    rows = {r["volume_id"]: r for r in split_doc["train"]
            + split_doc["validation"]}
    ds_tr = make_dataset(data_root, "train", "train", factory)
    ds_va = make_dataset(data_root, "train", "eval", factory)
    idx_tr = [(Path(p).relative_to(ds_tr.data_root).as_posix(), int(s))
              for p, s in ds_tr.index]
    idx_va = [(Path(p).relative_to(ds_va.data_root).as_posix(), int(s))
              for p, s in ds_va.index]
    require(idx_tr == idx_va, "DATASET_INDEX_DIVERGENT",
            "train-mode and eval-mode indexes differ")
    on_disk = {}
    for rel, s in idx_tr:
        on_disk.setdefault(Path(rel).name, []).append((rel, s))
    assert_no_holdout(on_disk, holdout, "train directory")
    require(set(on_disk) == set(rows), "DATASET_POPULATION",
            f"on disk {len(on_disk)} volumes vs manifest {len(rows)}; "
            f"missing {sorted(set(rows) - set(on_disk))[:3]} "
            f"extra {sorted(set(on_disk) - set(rows))[:3]}")
    for vid, ent in on_disk.items():
        r = rows[vid]
        require({rel for rel, _ in ent} == {r["file"]}, "SPLIT_RELPATH_MISMATCH",
                f"{vid}: {sorted({rel for rel, _ in ent})} vs {r['file']}")
        require([s for _, s in ent] == list(range(r["n_slices"])),
                "SPLIT_SLICE_COUNT", f"{vid}: {len(ent)} vs {r['n_slices']}")
    pos_tr = [i for i, (rel, _) in enumerate(idx_tr)
              if Path(rel).name in tr_ids]
    pos_va = [i for i, (rel, _) in enumerate(idx_va)
              if Path(rel).name in va_ids]
    require(len(pos_tr) == expect.train_slices
            and len(pos_va) == expect.validation_slices, "SPLIT_VIEW_COUNTS",
            f"{len(pos_tr)}/{len(pos_va)}")
    logger.info("[V05LTC] split views: train %d slices (%d vols), "
                "validation %d slices (%d vols)", len(pos_tr), len(tr_ids),
                len(pos_va), len(va_ids))
    return (SplitView(ds_tr, pos_tr, tr_ids, "train"),
            SplitView(ds_va, pos_va, va_ids, "validation"))


