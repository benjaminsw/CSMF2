class V05LTError(RuntimeError):
    def __init__(self, code: str, message: str,
                 taxonomy: str = "failed_validity"):
        super().__init__(f"{code}: {message}")
        self.code = code
        self.taxonomy = taxonomy


def fail(code: str, message: str, taxonomy: str = "failed_validity"):
    if taxonomy not in TAXONOMY:
        logger.error("[failed_validity] TAXONOMY_UNKNOWN: %r", taxonomy)
        raise V05LTError("TAXONOMY_UNKNOWN", repr(taxonomy))
    logger.error("[%s] %s: %s", taxonomy, code, message)
    raise V05LTError(code, message, taxonomy)


def require(cond: bool, code: str, message: str) -> None:
    if not cond:
        fail(code, message)


def utc_now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).isoformat(
        timespec="microseconds")


# ---------------------------------------------------------------------------
# Hashing
# ---------------------------------------------------------------------------
def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    try:
        with open(path, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                h.update(chunk)
    except OSError as exc:
        fail("FILE_UNREADABLE", f"{path}: {exc}")
    return h.hexdigest()


def read_sidecar(path: Path, code: str) -> str:
    """'<sha256>  <name>' sidecar -> the 64-hex sha256. Regular file only
    (lstat; symlinks, directories and missing entries refused); strict
    ASCII; every failure -> V05LTError(code)."""
    import stat as _stat
    path = Path(path)
    try:
        st = os.lstat(path)
    except OSError as exc:
        fail(code, f"{path}: sidecar missing ({exc.strerror})")
    require(_stat.S_ISREG(st.st_mode), code,
            f"{path}: sidecar is not a regular file")
    try:
        text = path.read_bytes().decode("ascii")
    except OSError as exc:
        fail(code, f"{path}: sidecar unreadable ({exc.strerror})")
    except UnicodeDecodeError as exc:
        fail(code, f"{path}: sidecar not ASCII ({exc.reason})")
    parts = text.split()
    target = path.name[:-len(".sha256")] if path.name.endswith(".sha256") \
        else None
    ok = (target is not None and len(parts) == 2 and parts[1] == target and
          len(parts[0]) == 64 and all(c in "0123456789abcdef"
                                      for c in parts[0]))
    require(ok, code, f"{path}: sidecar content malformed")
    return parts[0]


MODEL_STATE_SCHEMA = b"seqref-v05lt-model-state/1\n"


def model_state_sha256(state) -> str:
    """194 AM3-G1 model-state hash, independent of serialisation.
    Encoding: schema line; then for each key in sorted order:
    u64be(len(H)) || H, with H = canonical_json({name, dtype, shape});
    u64be(len(R)) || R, with R = raw bytes of the contiguous CPU tensor
    (host byte order, required little-endian)."""
    import torch
    if sys.byteorder != "little":
        fail("MODEL_STATE_BYTEORDER", f"host byte order {sys.byteorder}")
    sd = state.state_dict() if hasattr(state, "state_dict") else state
    require(isinstance(sd, dict) and len(sd) > 0, "MODEL_STATE_EMPTY",
            "state_dict is empty or not a dict")
    h = hashlib.sha256(MODEL_STATE_SCHEMA)
    for name in sorted(sd):
        t = sd[name]
        require(isinstance(t, torch.Tensor), "MODEL_STATE_NON_TENSOR",
                f"{name}: {type(t).__name__}")
        t = t.detach().to("cpu").contiguous()
        head = canonical_json({"name": name, "dtype": str(t.dtype),
                               "shape": list(t.shape)})
        raw = t.reshape(-1).view(torch.uint8).numpy().tobytes()
        h.update(len(head).to_bytes(8, "big"))
        h.update(head)
        h.update(len(raw).to_bytes(8, "big"))
        h.update(raw)
    return h.hexdigest()


