def verify_file(path: Path, expected_sha256: str, code: str = "INPUT") -> str:
    require(path.is_file(), f"{code}_MISSING", str(path))
    got = sha256_file(path)
    require(got == expected_sha256, f"{code}_HASH_MISMATCH",
            f"{path}: sha256 {got} != registered {expected_sha256}")
    return got


def verify_registered_inputs(inputs_dir: Path,
                             registry: dict = REGISTERED_INPUTS) -> dict:
    """Every registered input file in inputs_dir hashes to its registered
    value. Returns {name: sha256}."""
    out = {}
    for name, exp in sorted(registry.items()):
        out[name] = verify_file(inputs_dir / name, exp, "INPUT")
    logger.info("[V05LTC] %d registered inputs verified in %s",
                len(out), inputs_dir)
    return out


def verify_bank_npy(path: Path, file_sha256: str, array_sha256: str,
                    shape: tuple = BANK_SHAPE) -> np.ndarray:
    verify_file(path, file_sha256, "BANK")
    arr = np.load(path, allow_pickle=False)
    require(arr.dtype == np.float32 and tuple(arr.shape) == tuple(shape),
            "BANK_LAYOUT", f"{path.name}: {arr.dtype} {arr.shape}")
    require(bool(np.isfinite(arr).all()), "BANK_NON_FINITE", path.name)
    got = sha256_bytes(np.ascontiguousarray(arr).tobytes(order="C"))
    require(got == array_sha256, "BANK_ARRAY_HASH_MISMATCH",
            f"{path.name}: array sha256 {got} != registered {array_sha256}")
    return arr


